"""
hcm_crypto.py — symmetric encryption for secrets stored in PostgreSQL.

Cluster passwords and share credentials are stored Fernet-encrypted. The key is
derived from HCM_SECRET_KEY (any long random string, generated by install.py).
Every service that must read those secrets (collector, balancer, sentinel,
exports) and the dashboard (which writes them) receives the same variable.

Losing HCM_SECRET_KEY means the stored passwords cannot be recovered; they have
to be re-entered in the dashboard. Back the key up together with the database.

Canonical copy: shared/hcm_crypto.py — run tools/sync_shared.py after editing.
"""
from __future__ import annotations

import base64
import hashlib
import os

from cryptography.fernet import Fernet, InvalidToken

ENV_VAR = 'HCM_SECRET_KEY'


class SecretKeyMissing(RuntimeError):
    pass


def _fernet() -> Fernet:
    secret = os.environ.get(ENV_VAR, '').strip()
    if not secret:
        raise SecretKeyMissing(
            f'{ENV_VAR} is not set. It protects the cluster credentials stored in the '
            f'database; set it to a long random string (install.py generates one).'
        )
    key = base64.urlsafe_b64encode(hashlib.sha256(secret.encode('utf-8')).digest())
    return Fernet(key)


def encrypt(plain: str) -> str:
    """Encrypt *plain* and return a URL-safe token string."""
    return _fernet().encrypt(plain.encode('utf-8')).decode('ascii')


def decrypt(token: str) -> str:
    """Decrypt a token produced by encrypt(). Raises InvalidToken for a wrong key."""
    return _fernet().decrypt(token.encode('ascii')).decode('utf-8')


def key_configured() -> bool:
    return bool(os.environ.get(ENV_VAR, '').strip())


__all__ = ['encrypt', 'decrypt', 'key_configured', 'SecretKeyMissing', 'InvalidToken', 'ENV_VAR']
