"""
proxy_client.py — talk to a backup proxy (the container in this stack or a proxy VM in a
remote cluster) over its job API.

Transport security for remote proxies: either a pinned certificate fingerprint (self-signed
certificate generated by the proxy, pinned when the admin registers it) or normal CA
verification (customer certificate). Inside the stack plain http on the compose network is used.
"""
from __future__ import annotations

import hashlib
import socket
import ssl
import time
from urllib.parse import urlparse

import requests


class ProxyError(Exception):
    pass


def certificate_fingerprint(url: str, timeout: float = 10) -> str:
    """sha256 fingerprint (lowercase hex, no colons) of the certificate a https URL presents."""
    u = urlparse(url)
    if u.scheme != 'https':
        raise ProxyError('fingerprints apply to https URLs only')
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    with socket.create_connection((u.hostname, u.port or 443), timeout=timeout) as sock:
        with ctx.wrap_socket(sock, server_hostname=u.hostname) as tls:
            der = tls.getpeercert(binary_form=True)
    return hashlib.sha256(der).hexdigest()


def normalise_fingerprint(fp: str | None) -> str | None:
    if not fp:
        return None
    return fp.replace(':', '').replace(' ', '').strip().lower()


class ProxyClient:
    def __init__(self, url: str, token: str | None, *, tls_fingerprint: str | None = None,
                 tls_verify: bool = False, timeout: int = 30):
        self.url = url.rstrip('/')
        self.token = token or ''
        self.fingerprint = normalise_fingerprint(tls_fingerprint)
        self.tls_verify = tls_verify
        self.timeout = timeout
        self._pinned_ok = False

    # ------------------------------------------------------------------ transport
    def _check_pin(self) -> None:
        if self.fingerprint and not self._pinned_ok:
            seen = certificate_fingerprint(self.url)
            if seen != self.fingerprint:
                raise ProxyError(f'proxy certificate fingerprint {seen[:16]}… does not match the pinned {self.fingerprint[:16]}…')
            self._pinned_ok = True

    def _request(self, method: str, path: str, **kw):
        if self.url.startswith('https://'):
            if not self.fingerprint and not self.tls_verify:
                raise ProxyError('https proxy without a pinned certificate fingerprint or CA verification; probe it first')
            self._check_pin()
        headers = {'Authorization': f'Bearer {self.token}'} if self.token else {}
        verify = self.tls_verify if self.url.startswith('https://') else True
        try:
            r = requests.request(method, f'{self.url}{path}', headers=headers, timeout=kw.pop('timeout', self.timeout),
                                 verify=verify if not self.fingerprint else False, **kw)
        except requests.exceptions.RequestException as e:
            raise ProxyError(f'proxy unreachable at {self.url}: {e}') from e
        if r.status_code == 401:
            raise ProxyError('proxy rejected the token (401)')
        if r.status_code >= 400:
            try:
                detail = r.json().get('error', r.text[:200])
            except ValueError:
                detail = r.text[:200]
            raise ProxyError(f'proxy returned {r.status_code}: {detail}')
        return r.json() if r.text else None

    # ------------------------------------------------------------------ calls
    def health(self) -> dict:
        return self._request('GET', '/health') or {}

    def identity(self) -> dict:
        return self._request('GET', '/identity') or {}

    def submit(self, kind: str, body: dict) -> str:
        return self._request('POST', f'/jobs/{kind}', json=body)['id']

    def job(self, job_id: str) -> dict:
        return self._request('GET', f'/jobs/{job_id}')

    def cancel(self, job_id: str) -> None:
        self._request('DELETE', f'/jobs/{job_id}')

    def wait(self, job_id: str, on_progress=None, timeout: float = 8 * 3600, poll: float = 3) -> dict:
        """Poll until the job finishes. on_progress(progress_dict) when progress changes.
        Returns the job; raises ProxyError when it failed or was cancelled."""
        deadline = time.monotonic() + timeout
        last = None
        while time.monotonic() < deadline:
            j = self.job(job_id)
            p = j.get('progress') or {}
            if on_progress and p != last:
                on_progress(p)
                last = p
            if j['state'] == 'done':
                return j
            if j['state'] in ('failed', 'cancelled'):
                raise ProxyError(j.get('error') or f'proxy job {job_id} {j["state"]}')
            time.sleep(poll)
        try:
            self.cancel(job_id)
        finally:
            pass
        raise ProxyError(f'proxy job {job_id} did not finish within {timeout / 3600:.1f}h')


def match_vm_by_macs(macs: list[str], vms: list[dict]) -> dict | None:
    """The VM whose NICs carry one of the proxy's MAC addresses, or None."""
    wanted = {m.upper() for m in macs}
    for vm in vms:
        if any((n.get('macAddress') or '').upper() in wanted for n in vm.get('netDevs', [])):
            return vm
    return None
